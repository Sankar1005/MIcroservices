using OrderService.Api.Models;

namespace OrderService.Api.Repositories;

/// <summary>
/// Data access for ordering.Orders and ordering.OrderItems. Only active orders (IsActive = 1) are read or deleted.
/// </summary>
public interface IOrderRepository
{
    Task<IReadOnlyList<Order>> GetAllAsync(CancellationToken cancellationToken = default);

    /// <returns>The order with its items, or null.</returns>
    Task<Order?> GetByIdAsync(int id, CancellationToken cancellationToken = default);

    /// <summary>Saves the order and all its items in one transaction.</summary>
    /// <returns>The Id generated by the database.</returns>
    Task<int> CreateAsync(Order order, CancellationToken cancellationToken = default);

    /// <summary>Soft delete (cancel): sets IsActive = 0.</summary>
    /// <returns>False when no active order has this Id.</returns>
    Task<bool> DeleteAsync(int id, CancellationToken cancellationToken = default);
}
